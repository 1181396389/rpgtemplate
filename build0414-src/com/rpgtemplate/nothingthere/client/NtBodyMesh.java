package com.rpgtemplate.nothingthere.client;

import com.mojang.blaze3d.vertex.PoseStack;
import com.mojang.blaze3d.vertex.VertexConsumer;
import java.io.BufferedInputStream;
import java.io.DataInputStream;
import java.io.IOException;
import java.io.InputStream;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.util.ArrayList;
import java.util.List;
import net.minecraft.client.model.geom.ModelPart;
import org.joml.Matrix3f;
import org.joml.Matrix4f;
import org.joml.Quaternionf;
import org.joml.Vector3f;

/**
 * Draws the 一无所有 body as sculpted triangle meshes (generated by gen/gen_nt_mesh.py).
 *
 * Each part belongs to one vanilla frame (head, body, rightArm, leftArm, rightLeg, leftLeg). The mesh
 * is stored relative to that frame's pivot in model space, so the frame is posed with the vanilla part's
 * offset and rotation (same order as ModelPart.translateAndRotate). Colours are per vertex, and the
 * texture is a plain white texture, so no UV or pixel grid is involved.
 */
public final class NtBodyMesh {
    public static final int FRAME_HEAD = 0;
    public static final int FRAME_BODY = 1;
    public static final int FRAME_RIGHT_ARM = 2;
    public static final int FRAME_LEFT_ARM = 3;
    public static final int FRAME_RIGHT_LEG = 4;
    public static final int FRAME_LEFT_LEG = 5;

    private static final String DATA_PATH = "assets/rpgtemplate/models/nothing_there/body.bin";
    private static volatile List<Part> parts;

    private NtBodyMesh() {
    }

    /** One part: positions and normals in frame space, colours 0-255, triangle indices. */
    private record Part(String name, int frame, boolean goodbyeOnly, float[] pos, float[] nrm, int[] col, int[] idx) {
    }

    /** Draws all six frames. The arguments are the vanilla parts, which provide the offsets and rotations. */
    public static void drawBody(PoseStack pose, VertexConsumer vc, int light, int overlay,
                                ModelPart head, ModelPart body, ModelPart rightArm, ModelPart leftArm,
                                ModelPart rightLeg, ModelPart leftLeg, boolean goodbye) {
        drawFrame(pose, vc, light, overlay, head, FRAME_HEAD, goodbye);
        drawFrame(pose, vc, light, overlay, body, FRAME_BODY, goodbye);
        drawFrame(pose, vc, light, overlay, rightArm, FRAME_RIGHT_ARM, goodbye);
        drawFrame(pose, vc, light, overlay, leftArm, FRAME_LEFT_ARM, goodbye);
        drawFrame(pose, vc, light, overlay, rightLeg, FRAME_RIGHT_LEG, goodbye);
        drawFrame(pose, vc, light, overlay, leftLeg, FRAME_LEFT_LEG, goodbye);
    }

    /** Same transform order as ModelPart.translateAndRotate: offset, then Z, Y, X rotations. */
    private static void drawFrame(PoseStack pose, VertexConsumer vc, int light, int overlay,
                                  ModelPart part, int frame, boolean goodbye) {
        pose.m_85836_();
        pose.m_85837_(part.f_104200_ / 16.0, part.f_104201_ / 16.0, part.f_104202_ / 16.0);
        if (part.f_104205_ != 0.0F) {
            pose.m_252781_(new Quaternionf().rotationZ(part.f_104205_));
        }
        if (part.f_104204_ != 0.0F) {
            pose.m_252781_(new Quaternionf().rotationY(part.f_104204_));
        }
        if (part.f_104203_ != 0.0F) {
            pose.m_252781_(new Quaternionf().rotationX(part.f_104203_));
        }
        draw(pose, vc, light, overlay, frame, goodbye);
        pose.m_85849_();
    }

    /** Emits the triangles of one frame in the current pose. */
    private static void draw(PoseStack pose, VertexConsumer vc, int light, int overlay, int frame, boolean goodbye) {
        Matrix4f m = pose.m_85850_().m_252922_();
        Matrix3f nm = pose.m_85850_().m_252943_();
        Vector3f p = new Vector3f();
        Vector3f n = new Vector3f();
        for (Part part : parts()) {
            if (part.frame() != frame || (part.goodbyeOnly() && !goodbye)) {
                continue;
            }
            float[] pos = part.pos();
            float[] nrm = part.nrm();
            int[] col = part.col();
            for (int v : part.idx()) {
                int i = v * 3;
                m.transformPosition(pos[i], pos[i + 1], pos[i + 2], p);
                nm.transform(nrm[i], nrm[i + 1], nrm[i + 2], n);
                n.normalize();
                vc.m_5954_(p.x, p.y, p.z,
                    (col[i] & 0xFF) / 255.0F, (col[i + 1] & 0xFF) / 255.0F, (col[i + 2] & 0xFF) / 255.0F, 1.0F,
                    0.5F, 0.5F, overlay, light, n.x, n.y, n.z);
            }
        }
    }

    /** Number of triangles in the mesh, excluding goodbye-only parts unless requested. */
    public static int triangleCount(boolean goodbye) {
        int total = 0;
        for (Part part : parts()) {
            if (part.goodbyeOnly() && !goodbye) {
                continue;
            }
            total += part.idx().length / 3;
        }
        return total;
    }

    private static List<Part> parts() {
        List<Part> loaded = parts;
        if (loaded == null) {
            synchronized (NtBodyMesh.class) {
                if (parts == null) {
                    parts = load();
                }
                loaded = parts;
            }
        }
        return loaded;
    }

    private static List<Part> load() {
        InputStream raw = NtBodyMesh.class.getClassLoader().getResourceAsStream(DATA_PATH);
        if (raw == null) {
            throw new IllegalStateException("missing 一无所有 body mesh: " + DATA_PATH);
        }
        try (DataInputStream in = new DataInputStream(new BufferedInputStream(raw))) {
            byte[] magic = new byte[4];
            in.readFully(magic);
            if (!"NTM1".equals(new String(magic, StandardCharsets.US_ASCII))) {
                throw new IllegalStateException("bad 一无所有 body mesh header");
            }
            int count = in.readInt();
            List<Part> out = new ArrayList<>(count);
            for (int i = 0; i < count; i++) {
                byte[] name = new byte[in.readUnsignedByte()];
                in.readFully(name);
                int frame = in.readUnsignedByte();
                boolean goodbye = in.readUnsignedByte() != 0;
                int nv = in.readInt();
                int nf = in.readInt();
                float[] pos = new float[nv * 3];
                float[] nrm = new float[nv * 3];
                int[] col = new int[nv * 3];
                for (int v = 0; v < nv; v++) {
                    int k = v * 3;
                    pos[k] = in.readFloat();
                    pos[k + 1] = in.readFloat();
                    pos[k + 2] = in.readFloat();
                    nrm[k] = in.readFloat();
                    nrm[k + 1] = in.readFloat();
                    nrm[k + 2] = in.readFloat();
                    col[k] = in.readUnsignedByte();
                    col[k + 1] = in.readUnsignedByte();
                    col[k + 2] = in.readUnsignedByte();
                }
                int[] idx = new int[nf * 3];
                for (int j = 0; j < idx.length; j++) {
                    idx[j] = in.readInt();
                }
                out.add(new Part(new String(name, StandardCharsets.UTF_8), frame, goodbye, pos, nrm, col, idx));
            }
            return List.copyOf(out);
        } catch (IOException e) {
            throw new UncheckedIOException("failed to read 一无所有 body mesh", e);
        }
    }
}
